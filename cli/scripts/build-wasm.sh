#!/usr/bin/env sh
# Builds the @orkstage/scan npm package (Node.js target) into dist/scan-wasm/.
# Run inside the builder image (see README "Building in Docker"):
#   docker run --rm -v "$PWD:/work" -v orkstage-cargo-registry:/usr/local/cargo/registry \
#     -v orkstage-cli-target:/work/target -w /work orkstage/cli-builder:1.99 sh scripts/build-wasm.sh
set -eu

OUT=dist/scan-wasm
VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n 1)

cargo build -p orkstage-scan-wasm --release --target wasm32-unknown-unknown
rm -rf "$OUT"
mkdir -p "$OUT"
wasm-bindgen --target nodejs --out-dir "$OUT" --out-name orkstage_scan \
  target/wasm32-unknown-unknown/release/orkstage_scan_wasm.wasm

cat > "$OUT/package.json" <<EOF
{
  "name": "@orkstage/scan",
  "version": "$VERSION",
  "description": "OrkStage scan engine (WebAssembly): IaC and project files to a ScanReport and a platform/v1 template.",
  "license": "AGPL-3.0-only",
  "main": "orkstage_scan.js",
  "types": "orkstage_scan.d.ts",
  "files": [
    "orkstage_scan.js",
    "orkstage_scan.d.ts",
    "orkstage_scan_bg.wasm",
    "orkstage_scan_bg.wasm.d.ts",
    "README.md",
    "LICENSE"
  ],
  "engines": { "node": ">=18" },
  "sideEffects": false
}
EOF

cat > "$OUT/README.md" <<'EOF'
# @orkstage/scan

The OrkStage scan engine (`orkstage-scan`, Rust) compiled to WebAssembly for Node.js.
Generated by `cli/scripts/build-wasm.sh`; do not edit by hand.

```js
const { scanFiles, version } = require('@orkstage/scan');
const report = scanFiles(
  [{ path: 'docker-compose.yml', content: 'services:\n  db:\n    image: postgres:17\n' }],
  { templateName: 'shop' }, // optional: templateName, displayName, templateVersion, maxFileBytes
);
// report: ScanReport v1 (docs/specs/integration-api.md); report.template is platform/v1 YAML.
```

`scanFiles(files: { path: string; content: string }[], options?: ScanOptions): ScanReport` is
synchronous, does no I/O and throws only on malformed arguments.
EOF

cp LICENSE "$OUT/LICENSE"
ls -l "$OUT"
