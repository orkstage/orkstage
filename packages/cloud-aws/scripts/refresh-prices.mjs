// Regenerates src/prices.generated.ts (ADR 0010): AWS list prices per region from the public AWS
// price list files (no credentials needed), read with the same rules as the live Pricing API
// (src/price-list.ts). Run at release time, after building the package:
//   pnpm -C packages/cloud-aws build && node packages/cloud-aws/scripts/refresh-prices.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { albHourly, regionalPrices } from '../dist/price-list.js';

const REGIONS = [
  'us-east-1', 'us-east-2', 'us-west-2', 'ca-central-1', 'sa-east-1',
  'eu-west-1', 'eu-west-2', 'eu-central-1', 'ap-south-1', 'ap-southeast-1', 'ap-southeast-2', 'ap-northeast-1',
];
const SERVICES = { ecs: 'AmazonECS', rds: 'AmazonRDS', cache: 'AmazonElastiCache', elb: 'AWSELB' };

async function offer(service, region) {
  const url = `https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/${service}/current/${region}/index.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${service} ${region}: HTTP ${res.status}`);
  return res.json();
}

async function docsFor(region) {
  const entries = await Promise.all(Object.entries(SERVICES).map(async ([key, service]) => [key, await offer(service, region)]));
  return Object.fromEntries(entries);
}

const docs = {};
for (const region of REGIONS) {
  docs[region] = await docsFor(region);
  process.stdout.write(`${region} `);
}
const usAlb = albHourly(docs['us-east-1'].elb);
const table = {};
for (const [region, d] of Object.entries(docs)) {
  for (const [capability, prices] of Object.entries(regionalPrices(d, usAlb))) (table[capability] ??= {})[region] = prices;
}
const asOf = Object.values(docs)
  .flatMap((d) => Object.values(d).map((doc) => doc.publicationDate))
  .filter(Boolean)
  .sort()
  .at(-1)
  ?.slice(0, 10);

const out = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/refresh-prices.mjs from the public AWS price list (ADR 0010). Do not edit.
import type { RegionalPricing } from '@orkstage/cloud-core';

/** Date of the newest price list file read. */
export const AWS_PRICES_AS_OF = '${asOf}';

/** List prices per capability and region, on demand, USD per month (730 hours). */
export const AWS_REGIONAL_PRICES: Record<string, Record<string, RegionalPricing>> = ${JSON.stringify(table, null, 2)};
`;
const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'prices.generated.ts');
writeFileSync(file, out);
console.log(`\nwrote ${file} (as of ${asOf})`);
