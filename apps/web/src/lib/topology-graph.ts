import type { PreviewDto, ResourceDto } from '@co/contracts';
import { buildDependencyGraph, environmentTemplate } from '@co/templates';

/**
 * Topology edges for an instance. Imported lazily (diagram chunk / "Copy as Mermaid" click) so
 * @co/templates stays out of the instance page's initial bundle.
 */
export interface TopologyEdge {
  id: string;
  from: string;
  to: string;
  kind: 'connectivity' | 'dependency';
  label?: string;
  crossCloud?: boolean;
}

/** The cloud a resource effectively runs on (mock resources count as the cloud they simulate). */
export function effectiveProvider(r: Pick<ResourceDto, 'provider' | 'simulatedProvider'>): string {
  return r.simulatedProvider ?? r.provider;
}

export function topologyEdges(
  resources: ResourceDto[],
  document: Record<string, unknown> | null | undefined,
  connectivity: PreviewDto['connectivity'] | null | undefined,
): TopologyEdge[] {
  const byId = new Map(resources.map((r) => [r.resourceId, r]));
  const edges: TopologyEdge[] = [];
  const linked = new Set<string>();

  const parsed = document ? environmentTemplate.safeParse(document) : null;
  const template = parsed?.success ? parsed.data : null;

  const conn =
    connectivity && connectivity.length > 0
      ? connectivity.map((c) => ({ from: c.from, to: c.to, label: c.strategy, crossCloud: c.crossCloud, protocol: c.protocol }))
      : (template?.spec.connectivity ?? []).map((c) => {
          const a = byId.get(c.from);
          const b = byId.get(c.to);
          return { from: c.from, to: c.to, label: `${c.protocol} · ${c.mode}`, crossCloud: !!a && !!b && effectiveProvider(a) !== effectiveProvider(b), protocol: c.protocol };
        });

  conn.forEach((c, i) => {
    if (!byId.has(c.from) || !byId.has(c.to)) return;
    linked.add(`${c.from}>${c.to}`);
    edges.push({ id: `conn-${i}-${c.from}-${c.to}`, from: c.from, to: c.to, kind: 'connectivity', label: c.label, crossCloud: c.crossCloud });
  });

  if (template) {
    for (const [from, deps] of buildDependencyGraph(template)) {
      for (const to of deps) {
        if (!byId.has(from) || !byId.has(to) || linked.has(`${from}>${to}`)) continue;
        edges.push({ id: `dep-${from}-${to}`, from, to, kind: 'dependency' });
      }
    }
  }
  return edges;
}

const mid = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_');
const mlabel = (s: string) => s.replace(/"/g, '#quot;').replace(/[<>]/g, '');

/**
 * Mermaid `flowchart LR` text with nested subgraphs per provider → target → region.
 * Solid arrows: connectivity; thick arrows: cross-cloud connectivity; dotted: dependency.
 */
export function topologyToMermaid(resources: ResourceDto[], edges: TopologyEdge[], targetNames: Map<string, string>): string {
  const lines = ['flowchart LR', '  %% Generated by OrkStage. Solid: connectivity · thick: cross-cloud · dotted: dependency'];
  const tree = new Map<string, Map<string, Map<string, ResourceDto[]>>>();
  for (const r of resources) {
    const p = r.simulatedProvider ? `${r.simulatedProvider} (simulated)` : r.provider;
    const t = tree.get(p) ?? new Map<string, Map<string, ResourceDto[]>>();
    const g = t.get(r.targetId) ?? new Map<string, ResourceDto[]>();
    g.set(r.region, [...(g.get(r.region) ?? []), r]);
    t.set(r.targetId, g);
    tree.set(p, t);
  }
  for (const [provider, targets] of tree) {
    lines.push(`  subgraph P_${mid(provider)}["${mlabel(provider)}"]`);
    for (const [targetId, regions] of targets) {
      lines.push(`    subgraph T_${mid(targetId)}["${mlabel(targetNames.get(targetId) ?? `target ${targetId.slice(0, 8)}`)}"]`);
      for (const [region, list] of regions) {
        lines.push(`      subgraph R_${mid(targetId)}_${mid(region)}["${mlabel(region)}"]`);
        for (const r of list) lines.push(`        ${mid(r.resourceId)}["${mlabel(r.resourceId)}<br/>${mlabel(r.capabilityName)}"]`);
        lines.push('      end');
      }
      lines.push('    end');
    }
    lines.push('  end');
  }
  for (const e of edges) {
    const a = mid(e.from);
    const b = mid(e.to);
    if (e.kind === 'dependency') lines.push(`  ${a} -.-> ${b}`);
    else if (e.crossCloud) lines.push(`  ${a} ==>|"${mlabel(e.label ?? 'cross-cloud')}"| ${b}`);
    else lines.push(e.label ? `  ${a} -->|"${mlabel(e.label)}"| ${b}` : `  ${a} --> ${b}`);
  }
  return `${lines.join('\n')}\n`;
}
